import os
import time
from typing import Optional


def _optional_int(name: str) -> Optional[int]:
    value = os.environ.get(name, "").strip()
    if not value:
        return None
    try:
        return int(value)
    except ValueError as exc:
        raise ValueError(f"{name} must be an integer; received {value!r}") from exc


def _int_list(name: str) -> list[int]:
    raw = os.environ.get(name, "").strip()
    if not raw:
        return []
    result = []
    for item in raw.replace(",", " ").split():
        try:
            result.append(int(item))
        except ValueError as exc:
            raise ValueError(
                f"{name} must contain Telegram numeric user IDs separated by spaces"
            ) from exc
    return result


def _as_bool(name: str, default: bool = False) -> bool:
    raw = os.environ.get(name)
    if raw is None:
        return default
    return raw.strip().lower() in {"1", "true", "yes", "y", "on"}


class Config:
    # Required Telegram credentials. No placeholder credentials are embedded.
    API_ID = _optional_int("API_ID") or 0
    API_HASH = os.environ.get("API_HASH", "").strip()
    BOT_TOKEN = os.environ.get("BOT_TOKEN", "").strip()

    # MongoDB connection. DB_URL must be set in the hosting environment.
    DB_NAME = os.environ.get("DB_NAME", "autorenamebot").strip() or "autorenamebot"
    DB_URL = os.environ.get("DB_URL", "").strip()

    # Render supplies PORT automatically. Keep it numeric for aiohttp.
    PORT = _optional_int("PORT") or 10000

    BOT_UPTIME = time.time()
    START_PIC = os.environ.get(
        "START_PIC", "https://graph.org/file/29a3acbbab9de5f45a5fe.jpg"
    ).strip()

    # Configure these IDs in the host dashboard. No developer IDs are hardcoded.
    ADMIN = _int_list("ADMIN")
    LOG_CHANNEL = _optional_int("LOG_CHANNEL")
    DUMP_CHANNEL = _optional_int("DUMP_CHANNEL")
    SUPPORT_CHAT = _optional_int("SUPPORT_CHAT")

    # Optional subscription gate; empty means it is disabled.
    FORCE_SUB_CHANNELS = [
        item.strip().lstrip("@")
        for item in os.environ.get("FORCE_SUB_CHANNELS", "").split(",")
        if item.strip()
    ]

    # WEBHOOK is retained for compatibility; this app uses it to enable its
    # lightweight HTTP health endpoint, not Telegram webhook delivery.
    WEBHOOK = _as_bool("WEBHOOK", default=True)


